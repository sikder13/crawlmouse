/**
 * The access matrix's rows (CC-37 D1): for each route handler, each server entry file that reads
 * data and each file that opens a service-role client, whom it acts for, the check that gates it and
 * the test that proves the check. access-matrix.test.ts holds every row to the disk and the code;
 * docs/ops/access-matrix.md is rendered from this file.
 *
 * A route or page whose file also opens a service-role client is written once, in `ROUTES` or
 * `ENTRIES` with its `calls`, and appears in both tables. Within each kind, v2 account, site, seat,
 * report, billing and client-contact surfaces come first, then the rest.
 */
import type { AccessRow, Check, GateKind, Proof } from './access-matrix.types';

/** Holes found by CC-37 and not yet closed. Each is a `hole` on at least one row. */
export const KNOWN_OPEN: readonly string[] = ['Q16', 'Q25'];

const web = (p: string) => `apps/web/${p}`;
const at = (file: string, marker: string): Check => ({ file: web(file), marker });
const by = (file: string, test: string): Proof => ({ file: web(file), test });
const repo = (file: string, test: string): Proof => ({ file, test });

interface Spec {
  readonly path: string;
  readonly v2: boolean;
  readonly identity: string;
  readonly gate: GateKind;
  readonly action?: string;
  readonly detail: string;
  readonly check?: Check;
  readonly callers?: readonly string[];
  readonly proof: Proof;
  /** Service-role clients the file opens; set, the file also has a service-client row. */
  readonly calls?: number;
  readonly hole?: string;
}

