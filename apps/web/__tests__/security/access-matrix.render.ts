/**
 * Renders docs/ops/access-matrix.md from the rows in access-matrix.data.ts (OPERATING-RULES §10: prose
 * about measured data is built from the data). Run with `--write` to update the file:
 *   pnpm --filter @crawlmouse/web exec tsx __tests__/security/access-matrix.render.ts --write
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ACCESS_ROWS, KNOWN_OPEN } from './access-matrix.data';
import { ADMIN_ROOTS, type AccessRow } from './access-matrix.types';

// `import.meta.url`, not `__dirname`: the package is an ES module, so `tsx` (the --write command)
// has no `__dirname`.
export const DOC_PATH = fileURLToPath(
  new URL('../../../../docs/ops/access-matrix.md', import.meta.url),
);

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function gateText(r: AccessRow): string {
  const g = r.gate === 'seat_may' ? `seat_may(${r.action})` : r.gate;
  return r.hole ? `${g} — **open: ${r.hole}**` : g;
}

function checkText(r: AccessRow): string {
  if (r.check) {
    const call = r.check.arg ? `.${r.check.marker}('${r.check.arg}', …)` : r.check.marker;
    return `\`${call}\` in \`${r.check.file}\``;
  }
  if (r.callers) {
    const list = r.callers.map((c) => `\`${c}\``).join(', ');
    return r.publicCallers ? `${list}; public callers: ${r.publicCallers}` : list;
  }
  return '—';
}

function table(rows: readonly AccessRow[], withCalls: boolean): string {
  const head = withCalls
    ? '| File | Clients | Acts for | Gate | Where | What | Proved by |\n|---|---|---|---|---|---|---|'
    : '| Path | Acts for | Gate | Where | What | Proved by |\n|---|---|---|---|---|---|';
  const lines = rows.map((r) =>
    [
      `\`${r.path}\``,
      ...(withCalls ? [String(r.calls ?? '')] : []),
      r.identity,
      gateText(r),
      checkText(r),
      r.detail,
      `\`${r.proof.file}\` › ${r.proof.test}`,
    ]
      .map(cell)
      .join(' | '),
  );
  return [head, ...lines.map((l) => `| ${l} |`)].join('\n');
}

export function render(rows: readonly AccessRow[] = ACCESS_ROWS): string {
  const of = (k: AccessRow['kind']) => rows.filter((r) => r.kind === k);
  const counts = (['route', 'entry', 'service-client'] as const).map((k) => of(k).length);
  const gates = new Map<string, number>();
  for (const r of rows) gates.set(r.gate, (gates.get(r.gate) ?? 0) + 1);
  return `<!-- Generated by apps/web/__tests__/security/access-matrix.render.ts. Do not edit by hand. -->
# Access matrix

Who each part of the app acts for, what decides whether it may read or write, and a test of it.
Rendered from \`apps/web/__tests__/security/access-matrix.data.ts\`. The checks below are made by
\`pnpm --filter @crawlmouse/web exec vitest run __tests__/security/access-matrix.test.ts\`, which fails
when:

- a route folder under \`apps/web/app\`, a server entry file there that reads data, or a non-test file
  under ${ADMIN_ROOTS.map((r) => `\`${r}\``).join(', ')} that opens a service-role client has no row. A
  service-role client is counted by binding: a call of anything imported from
  \`apps/web/lib/supabase/admin\` (under any name, or through a namespace), or a \`createClient\` given
  \`SUPABASE_SERVICE_ROLE_KEY\` directly, by \`process.env['…']\` or through a local variable;
- a row's check is not a call in its file or a file it imports, or its answer is not read: a bare
  statement, \`void\`, a binding whose name is not read elsewhere in the file, or a result of which
  only the \`error\` is read (\`{ data: allowed, error }\` with \`allowed\` unread, \`res.error\`,
  \`(await …).error\`); a string is a check only as \`.rpc('<name>')\`, or as the filter the row names
  (\`.eq('audit_id', …)\`);
- a row's proof is not one running \`it\`/\`test\` of that whole title (no \`describe\`, \`.skip\`,
  \`.todo\`, \`.fails\`, \`.only\`, \`.skipIf\`, \`.runIf\`, nor a test inside a \`describe\` or \`suite\`
  carrying one), in a test file that imports the row's file or its check's file; a \`caller\` row's
  proof is the matrix's caller check instead;
- a chain of importers from a \`caller\` row does not end at a row with another gate (a \`public\` row
  ends one only where the row says why, under "public callers"), or loops;
- or this file differs from the render.

Not read: anything outside those roots, \`scripts/\` included. The files there that name the
service-role factory or key: \`grep -rlE "supabaseAdmin|SUPABASE_SERVICE_ROLE_KEY" scripts\`.

Rows: ${counts[0]} route handlers, ${counts[1]} server entry files that read data, ${counts[2]} files that
open a service-role client. By gate: ${[...gates]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([g, n]) => `${g} ${n}`)
    .join(', ')}. Open holes: ${KNOWN_OPEN.length === 0 ? 'none' : KNOWN_OPEN.join(', ')}.

What this cannot see: a signed-in seat calling PostgREST or an RPC directly with its own session,
which row security and grants decide (\`infra/supabase/migrations\`, tested by the \`v2-0*\` suites);
and whether the named test is the one that fails when a check's refusal is removed. The matrix finds
the check and the test; a mutation that removes the refusal measures the rest, and is recorded with
the change that names the proof, not here.

Regenerate: \`pnpm --filter @crawlmouse/web exec tsx __tests__/security/access-matrix.render.ts --write\`.

## Route handlers

${table(of('route'), false)}

## Server entry files that read data

${table(of('entry'), false)}

## Files that open a service-role client

${table(of('service-client'), true)}
`;
}

if (process.argv.includes('--write')) {
  writeFileSync(DOC_PATH, render());
}
