function sqlSection(): string {
  const mig = resolve(MIGRATIONS_DIR, MIGRATION_006B);
  const rev = resolve(ROLLBACKS_DIR, revertFile(MIGRATION_006B));
  return [
    '## The SQL for approval',
    '',
    'The SQL of 003 and 007, with their hashes, is in `docs/specs/v2/06-check-tables.md`.',
    '',
    table(
      ['File', 'sha256'],
      [
        [code(`infra/supabase/migrations/${MIGRATION_006B}`), code(sha256(mig))],
        [code(`infra/supabase/rollbacks/${revertFile(MIGRATION_006B)}`), code(sha256(rev))],
      ],
    ),
    '',
    '<details><summary>Migration SQL</summary>',
    '',
    '````sql',
    readFileSync(mig, 'utf8').trimEnd(),
    '````',
    '',
    '</details>',
    '',
    '<details><summary>Revert SQL</summary>',
    '',
    '````sql',
    readFileSync(rev, 'utf8').trimEnd(),
    '````',
    '',
    '</details>',
    '',
  ].join('\n');
}

export async function buildDataFoundationsSpec(): Promise<string> {
  const db = await freshDb();
  await applyAllMigrations(db);
  const md = [
    INTRO,
    await lineageSection(db),
    VANTAGE,
    statusSection(),
    await partitionSection(db),
    RETENTION,
    await ledgerSection(db),
    await usageSection(db),
    MISMATCHES,
    FOLLOW_UPS,
    RUNBOOK,
    sqlSection(),
  ].join('\n');
  const config = (await resolveConfig(SPEC_06B_PATH)) ?? {};
  return format(md, { ...config, filepath: SPEC_06B_PATH });
}
