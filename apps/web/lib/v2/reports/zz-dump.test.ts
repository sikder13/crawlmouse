import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
const out: string[] = [];
const console = { log: (...a: unknown[]) => out.push(a.map((x) => typeof x === 'string' ? x : JSON.stringify(x)).join(' ')) };
import { fixture } from '../fixtures';
import { resultView, partialNotice } from '../view/result';
import { accessView } from '../view/segment/access';
import { nojsView } from '../view/segment/nojs';
import { structureView } from '../view/segment/structure';
import { contentView } from '../view/segment/content';
import { signalsView } from '../view/segment/signals';
import { changesView } from '../view/segment/changes';
const name = (process.env.DUMP_FIXTURE ?? 'bad-site') as 'bad-site';
const d = fixture(name);
const checks = d.checks.filter((c) => c.status === 'finished' || c.status === 'partial');
console.log(checks.map((c) => [c.id, c.status, c.finished_at, c.previous_check_id, c.trigger]));
const id = process.env.DUMP_CHECK ?? checks.at(-1)!.id;
const strip = (v: unknown): unknown => JSON.parse(JSON.stringify(v, (k, val) => (k === 'positions' || k === 'nodes' || k === 'prompt' || k === 'packet' || k==='handoff' ? undefined : val)));
const r = resultView(d, id, { map: null, plan: 'pro' });
console.log(JSON.stringify(strip(r), null, 1));
console.log('PARTIAL', partialNotice(d, id));
const a = accessView(d, id, { plan: 'pro' });
console.log(JSON.stringify(strip({ headline: a.headline, tiles: a.tiles, method: a.method, columns: a.columns, groups: a.groups.map(g=>({title:g.title,note:g.note,rows:g.rows.map(r=>({ua:r.ua,verdict:r.verdict,text:r.text,cause:r.cause}))})), footnote: a.footnote, noEvidence: a.noEvidence, fixes: a.fixes }), null, 1));
const n = nojsView(d, id, { plan: 'pro' });
console.log(JSON.stringify(strip({ headline: n.headline, tiles: n.tiles, measuredSet: n.measuredSet, recordLine: n.recordLine, rows: n.rows.slice(0,2).map(x=>({...x,evidence:undefined})), fixesNote: n.fixesNote }), null, 1));
const s = structureView(d, id, { plan: 'pro' }, null);
console.log(JSON.stringify(strip({ headline: s.headline, tiles: s.tiles, orphans: s.orphans }), null, 1));
const c = contentView(d, id, { plan: 'pro' });
console.log(JSON.stringify(strip({ headline: c.headline, tiles: c.tiles, grid: c.grid && {title:c.grid.title, columns:c.grid.columns, rows:c.grid.rows.map(r=>({label:r.label,why:r.why,cells:r.cells.map(x=>x&&x.text)})), notChecked:c.grid.notChecked}, coverage: c.coverage, fixesNote: c.fixesNote }), null, 1));
const g = signalsView(d, id, { plan: 'pro' });
console.log(JSON.stringify(strip({ headline: g.headline, body: g.body, tiles: g.tiles, rows: g.rows, coverage: g.coverage }), null, 1));
const ch = changesView(d, id, { plan: 'pro' });
console.log(JSON.stringify(strip({ state: ch.state, headline: ch.headline, body: ch.body, tiles: ch.tiles, rows: ch.rows, history: ch.history, coverage: ch.coverage }), null, 1));

it('dump', () => { writeFileSync(process.env.DUMP_OUT!, out.join('\n')); });
