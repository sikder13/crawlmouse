import { FixTypeSchema, UNMEASURED_VERDICTS, VerdictSchema } from '@crawlmouse/types/v2';
import { HUB_MAP_CAP, HUB_MIN_INBOUND } from '../layout/hubs.js';
import {
  ACCESS,
  MIN_GRADE_SCORE_DELTA,
  QUOTED_LINE_BYTES,
  QUOTED_LINES,
  VERDICT_PHRASE,
} from './changes.js';
import { EVENT_OF, LIFECYCLE, OUTCOMES, PRIORS, ROW_OF, type Action } from './lifecycle.js';
import { LCS_CELL_LIMIT } from './robots-diff.js';
import { BAD_AI_READABILITY_POINTS, BAD_TECHNICAL_SEO_POINTS } from './severity.js';
import { COVERAGE_DEPENDENCE, FIX_SECTION, FIX_SUBJECT } from './subjects.js';

export const SPEC_URL = new URL(
  '../../../../../docs/specs/v2/19-diff-lifecycle.md',
  import.meta.url,
);

const ACTION_TEXT: Readonly<Record<Action, string>> = {
  untouched: 'no change',
  insert: 'a new fix, `open`',
  remeasure: 'last measurement recorded; nothing else changes',
  refresh:
    'rank, effect, packet, affected pages, before/after, confidence and last measurement refreshed',
  reopen: 'the fix becomes `reopened`, its measured fields refreshed; `first_seen` kept',
  verify: 'the fix becomes `verified_resolved`, its rank cleared',
  unable_to_verify: 'the fix becomes `unable_to_verify`, last state `indeterminate`',
};

const code = (s: string) => `\`${s}\``;
const or = (s: string | null) => (s === null ? 'none' : code(s));

function table(head: string[], rows: string[][]): string {
  const width = head.map((h, k) => Math.max(h.length, ...rows.map((r) => r[k]!.length)));
  const line = (cells: string[]) => `| ${cells.map((c, k) => c.padEnd(width[k]!)).join(' | ')} |`;
  return [line(head), line(width.map((w) => '-'.repeat(w))), ...rows.map(line)].join('\n');
}

function lifecycleTable(): string {
  const rows = OUTCOMES.flatMap((outcome) =>
    PRIORS.map((prior) => {
      const action = LIFECYCLE[outcome][prior];
      return [
        code(outcome),
        code(prior),
        ACTION_TEXT[action],
        or(EVENT_OF[action]),
        or(ROW_OF[action]),
      ];
    }),
  );
  return table(
    ['Outcome on this check', 'Fix before', 'Result', 'Event appended', 'Change row'],
    rows,
  );
}

function subjectTable(): string {
  return table(
    ['Fix type', 'Section', 'Change subject', 'Measurement depends on'],
    FixTypeSchema.options.map((t) => [
      code(t),
      code(FIX_SECTION[t]),
      code(FIX_SUBJECT[t]),
      COVERAGE_DEPENDENCE[t] === null ? 'neither' : code(COVERAGE_DEPENDENCE[t]!),
    ]),
  );
}

function verdictTable(): string {
  return table(
    ['Verdict', 'Reads in a summary as', 'Counts as access'],
    VerdictSchema.options
      .filter((v) => !UNMEASURED_VERDICTS.includes(v))
      .map((v) => [code(v), VERDICT_PHRASE[v], ACCESS.includes(v) ? 'yes' : 'no']),
  );
}

export function renderDiffSpec(): string {
  const unmeasured = UNMEASURED_VERDICTS.map(code).join(' or ');
  return `# SPEC 19 — change detection, the fix lifecycle and the map layout

> Generated by \`pnpm --filter @crawlmouse/engine exec tsx src/v2/diff/write-spec.ts\`. Do not edit it by hand: \`packages/engine/src/v2/diff/spec.test.ts\` fails when this file differs from what the generator writes.

\`diffCheck\` (\`packages/engine/src/v2/diff/diff.ts\`) turns two checks of the same site into what changed: new or updated fixes, the \`FixEvent\`s appended to their history, and \`Change\` rows. It is pure (no database, queue or network) and runs on the CC-11 contract (\`packages/types/src/v2\`). CC-20 calls it once a check is graded. Its tests: \`pnpm --filter @crawlmouse/engine exec vitest run src/v2/diff\`.

## Input

- The check, and the last graded check of the site before it (none on a site's first). Beside each \`Check\` record, the pipeline passes what the contract does not store: the page cap the crawl ran under, robots.txt as it was read (\`null\` when it could not be read), and the fix types whose detectors ran.
- The site's fixes and their events. A fix's stored status must be the consequence of its last event (none is \`open\`); \`diffCheck\` throws otherwise.
- The fingerprints each check's detectors reported \`indeterminate\`, so a new fix is not said to have appeared since a check that could not measure it.
- One outcome per fingerprint the detectors reported: \`detected\` with the fix's measured fields, \`not_detected\` or \`indeterminate\`. A fingerprint with no outcome is \`absent\`.

## The lifecycle

From \`LIFECYCLE\` in \`lifecycle.ts\`. A row in the last column is written only when the rules under "When a row is written" allow it. \`lifecycle.test.ts\` has one test per row of this table. The \`absent\` / \`none\` row is never read: a fingerprint with no fix and no outcome is not visited. One cell departs from the brief, which says nothing happens: \`not_detected\` on a \`verified_resolved\` fix records the check as the fix's last measurement (\`remeasure\`). The check did measure it, and without the record a regression on a later check would not count as measured by the check before it, so it would write no row.

${lifecycleTable()}

## When a row is written

- **First graded check of a site.** A fix it opens writes an \`opened\` row. Grade, crawler, robots.txt and deploy rows need a check to compare with, so there are none.
- **Different \`grade_version\`.** One row, kind \`changed\`, subject \`grade\`, summary "New baseline: grading changed from <old> to <new>; earlier results are not compared.", and no other row. Fixes still move through the lifecycle.
- **Coverage changed.** The page cap, or the sample (method, \`max_pages\` or pages sampled). For a fix type whose measurement depends on what changed (table below), \`not_detected\` is read as \`indeterminate\`, so the fix is not resolved, and the fix writes no row, an opening included (the brief: a coverage change suppresses per-fix change rows for coverage-dependent fixes).
- **Both checks measured the subject.** An existing fix writes a row when its last measurement was the previous check and found it or found it gone; a new fix, when the previous check ran its detector and did not report its fingerprint \`indeterminate\`. A fix that is \`unable_to_verify\` writes its row on the next check that measures it: the check that set that status could not measure it, and the table above gives that measurement a row.
- **Ranks.** After the lifecycle, the site's live fixes (all but \`verified_resolved\`) are ranked 1 to n: the fixes found on this check first, in the detector's order, then the live fixes it did not measure, by their stored rank; fix number breaks a tie in either. No two share a rank, and a fix the check could not measure does not take a place ahead of one it found. A fix whose rank alone moved is returned with the rest.
- **A crawler-access fix and its crawler.** When a crawler named by the fix has a row of its own that moved the same way (both opened, or both resolved) and tells no other fix, the fix is told on that row (\`fix_id\`) instead of a second row.
- **A fix the owner touched after the check finished.** When a fix has an event dated at or after this check's finish (marked done since), the check's outcome for it counts as \`absent\`: the measurement is older than the claim, and the next check settles it.

## Fix types

From \`FIX_SECTION\`, \`FIX_SUBJECT\` and \`COVERAGE_DEPENDENCE\` in \`subjects.ts\`. The subject follows the section, except where a type has a narrower one. Which coverage a type depends on is provisional until the detectors (CC-15/16/17) state it.

${subjectTable()}

## Rows that are not a fix

- **Grade.** One row, kind \`changed\`, when a grade measured on both checks moved letter or by at least ${MIN_GRADE_SCORE_DELTA} point (\`MIN_GRADE_SCORE_DELTA\`, provisional until the ground-truth corpus, CC-18). A refused Technical SEO grade or a withheld AI readability grade is not measured. The row carries each grade that moved in \`grade_deltas\`.
- **Crawler.** One row per crawler both checks tested whose verdict moved, unless either verdict is ${unmeasured}. \`opened\` when it lost access, \`resolved\` when it regained it, \`changed\` otherwise. A move to or from \`disallowed_by_robots\` is placed in robots.txt and quotes the robots.txt diff when both checks read the file.
- **robots.txt.** When both checks read robots.txt, the text changed, and no crawler row quotes the diff: one \`changed\` row, subject \`crawler_access\`. The diff is the literal line diff (\`robots-diff.ts\`): lines are compared as written, except line endings, and a line that moved shows as removed and added. Past ${LCS_CELL_LIMIT.toLocaleString('en')} cells (\`LCS_CELL_LIMIT\`) the changed middle is quoted whole: a true diff, not the shortest. A row quotes at most ${QUOTED_LINES} lines each way, each cut to ${QUOTED_LINE_BYTES} bytes, and its cause says how many were not quoted and how many were cut.
- **Deploy.** One \`changed\` row, subject \`deploy\`, when the detected stack (frontend name, version and router; CMS; edge vendor) differs between two checks that both detected one. How a part was detected is evidence, not the stack, and is not compared.

How a verdict reads in a crawler row's summary, from \`VERDICT_PHRASE\` and \`ACCESS\` in \`changes.ts\`:

${verdictTable()}

## Severity

\`severityOf\` (\`severity.ts\`, ARCH-2 §4.5): an \`opened\` change whose fix is worth at least ${BAD_AI_READABILITY_POINTS} points of AI readability or ${BAD_TECHNICAL_SEO_POINTS} of technical SEO is \`bad\`; another \`opened\` change is \`warn\`; a \`resolved\` one is \`info\`; a \`changed\` row has none. Both thresholds are provisional until CC-18. It is computed where it is needed and not stored: \`Change\` has no field for it.

## The map layout

The force layout of the crawl screen is \`packages/engine/src/v2/layout/force-layout.ts\`, imported as \`@crawlmouse/engine/v2/layout\` by the web app (\`apps/web/lib/v2/map-layout.ts\` and its Web Worker) and by the server. \`apps/web/lib/v2/map-layout.golden.test.ts\` pins its output to what it drew before it moved; \`force-layout.test.ts\` lays out a 2,000-node graph twice and requires the same bytes inside 2 s.

The map a finished check stores is \`hubsAndNeighbours\` (\`hubs.ts\`): pages with at least ${HUB_MIN_INBOUND} inbound links, most-linked first, then the pages they link to, up to ${HUB_MAP_CAP} nodes, the home page kept; each hangs from its nearest kept ancestor on a breadth-first tree of the check's links.

## Contract follow-ups

What this step needed and the contract cannot hold. None is worked around in the contract.

- \`Change.severity\`: there is no field, so severity is computed, not stored.
- \`Fix.last_state\` cannot record \`indeterminate\` on an \`open\`, \`reopened\` or \`verified_resolved\` fix (\`LAST_STATE_FOR_STATUS\`), so an \`indeterminate\` outcome leaves those fixes untouched.
- A \`baseline\` value in \`ChangeKind\`: a new baseline is a \`changed\` grade row with no \`grade_deltas\`, told apart by its summary.
- \`Change\` has no field saying a fix was reopened; the event history holds it, and the row's cause says it in words.
- \`Check\` does not carry the page cap or the robots.txt text; the pipeline passes them beside it.
- No \`ChangeSubject\` for a sitemap count change, and no threshold for a site-wide text-share drop; neither row is written.
`;
}
