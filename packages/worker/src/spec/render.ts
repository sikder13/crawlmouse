export async function prettierMarkdown(md: string, path: URL): Promise<string> {
  const config = (await resolveConfig(path.pathname)) ?? {};
  return format(md, { ...config, parser: 'markdown' });
}

/** The runbook with its generated section replaced by what the code renders now. */
export function withGeneratedSection(runbook: string): string {
  const start = runbook.indexOf(GENERATED_START);
  const end = runbook.indexOf(GENERATED_END);
  if (start < 0 || end < start) throw new Error('runbook: generated section markers missing');
  return `${runbook.slice(0, start + GENERATED_START.length)}\n\n${renderVerdictMeanings()}\n\n${runbook.slice(end)}`;
}
