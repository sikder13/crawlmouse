const code = (s: string | number) => `\`${s}\``;
const tags = (names: readonly string[]) => names.map((n) => code(`<${n}>`)).join(', ');
/** Each character, as its code point. */
const codePoints = (chars: string) =>
  [...chars]
    .map((c) => `U+${c.codePointAt(0)!.toString(16).toUpperCase().padStart(4, '0')}`)
    .join(', ');
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const kib = (bytes: number) =>
  bytes % (1024 * 1024) === 0 ? `${bytes / (1024 * 1024)} MiB` : `${bytes / 1024} KiB`;
const seconds = (ms: number) => (ms % 60_000 === 0 ? `${ms / 60_000} min` : `${ms / 1000} s`);

function table(header: string[], rows: string[][]): string {
  const line = (cells: string[]) => `| ${cells.map(cell).join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

function identityRow(role: string, id: Identity): string[] {
  const from = id.headers.find(([n]) => n === 'From')?.[1];
  return [
    role,
    id.token ?? '—',
    id.robotsToken ?? `ours: ${OUR_ROBOTS_TOKENS.join(', ')}`,
    code(id.userAgent),
    from ?? 'none',
  ];
}

function counts(c: Partial<Record<string, number>>): string {
  return Object.entries(c)
    .map(([verdict, n]) => `${verdict} ${n}`)
    .join(', ');
}

export function renderVerdictMeanings(): string {
  return table(
    ['Verdict', 'Means', 'Evidence on the row'],
    Object.entries(VERDICT_MEANINGS).map(([v, m]) => [code(v), m.means, m.evidence]),
  );
}

